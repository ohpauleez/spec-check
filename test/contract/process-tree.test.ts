import { mkdtemp, readFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { performance } from "node:perf_hooks";
import { describe, expect, it } from "vitest";
import fc from "fast-check";
import { isUtf8 } from "node:buffer";

import { runProcess, PROCESS_CLEANUP_ALLOWANCE_MS } from "../../src/adapters/process.js";
import { traceSpec } from "../support/spec-trace.js";

/** Observe running work, treating a reaped-or-zombie process as terminated. */
async function isRunning(pid: number): Promise<boolean> {
  try {
    process.kill(pid, 0);
    if (process.platform === "linux") {
      const stat = await readFile(`/proc/${String(pid)}/stat`, "utf8");
      return !/^\d+ \(.*\) [ZX] /u.test(stat);
    }
    return true;
  } catch { return false; }
}

describe("owned subprocess termination", () => {
  it.skipIf(process.platform === "win32").each(["timeout", "overflow", "parent-exit"] as const)("bounds %s while inherited pipes are held, and kills owned descendants", async (kind) => {
    traceSpec("CAT-OC-VERSION", "CAT-OC-VERSION-REJECT", "CAT-PROCESS-BOUND", "CAT-PROCESS-DESCENDANTS");
    const root = await mkdtemp(join(tmpdir(), "spec-check-tree-"));
    const pidFile = join(root, "pid");
    let descendant: number | undefined;
    try {
      const source = `const {spawn}=require('node:child_process'); const fs=require('node:fs');
        const c=spawn(process.execPath,['-e','setInterval(()=>{},1000)'],{stdio:'inherit'});
        fs.writeFileSync(${JSON.stringify(pidFile)}, String(c.pid));
        ${kind === "overflow" ? "setTimeout(()=>process.stdout.write('x'.repeat(100000)),100);" : ""}
        ${kind === "parent-exit" ? "process.exit(0);" : "setInterval(()=>{},1000);"}`;
      const started = performance.now();
      const result = await runProcess(process.execPath, ["-e", source], { timeoutMs: 400, maxOutputBytes: 1024 });
      expect(performance.now() - started).toBeLessThan(400 + PROCESS_CLEANUP_ALLOWANCE_MS + 500);
      expect(result.outputLimitExceeded).toBe(kind === "overflow");
      expect(result.timedOut).toBe(kind !== "overflow");
      descendant = Number(await readFile(pidFile, "utf8"));
      expect(Number.isSafeInteger(descendant)).toBe(true);
      expect(descendant).toBeGreaterThan(0);
      expect(await isRunning(descendant)).toBe(false);
    } finally {
      if (descendant !== undefined && await isRunning(descendant)) process.kill(descendant, "SIGKILL");
      await rm(root, { recursive: true, force: true });
    }
  });

  it.skipIf(process.platform === "win32")("settles after bounded pipe cleanup even if a descendant deliberately escapes ownership", async () => {
    traceSpec("CAT-OC-VERSION-REJECT", "CAT-PROCESS-PIPE-CLEANUP");
    const root = await mkdtemp(join(tmpdir(), "spec-check-escaped-"));
    const pidFile = join(root, "pid");
    let escaped: number | undefined;
    try {
      const source = `const c=require('node:child_process').spawn(process.execPath,['-e','setInterval(()=>{},1000)'],{stdio:'inherit',detached:true}); require('node:fs').writeFileSync(${JSON.stringify(pidFile)},String(c.pid)); setInterval(()=>{},1000);`;
      const started = performance.now();
      const result = await runProcess(process.execPath, ["-e", source], { timeoutMs: 400 });
      expect(result.timedOut).toBe(true);
      expect(performance.now() - started).toBeLessThan(400 + PROCESS_CLEANUP_ALLOWANCE_MS + 500);
      escaped = Number(await readFile(pidFile, "utf8"));
      expect(Number.isSafeInteger(escaped)).toBe(true);
      expect(escaped).toBeGreaterThan(0);
      // Escaped groups are explicitly outside adapter ownership. The test
      // cleans up its own fixture; their inherited handles cannot block return.
      expect(await isRunning(escaped)).toBe(true);
    } finally {
      if (escaped !== undefined && await isRunning(escaped)) process.kill(-escaped, "SIGKILL");
      await rm(root, { recursive: true, force: true });
    }
  });

  it("preserves strict UTF-8 validity for generated byte strings without a discarded decode", () => {
    traceSpec("RAE-FINAL-PROTO-ACK", "RAE-FINAL-VALIDATE");
    fc.assert(fc.property(fc.uint8Array({ maxLength: 1024 }), (bytes) => {
      let reference = true;
      try { new TextDecoder("utf-8", { fatal: true }).decode(bytes); } catch { reference = false; }
      expect(isUtf8(bytes)).toBe(reference);
    }), { numRuns: 300 });
  });

  it("decodes empty, Unicode, split multibyte, and invalid stderr bytes consistently", async () => {
    traceSpec("RAE-FINAL-PROTO-ACK");
    const result = await runProcess(process.execPath, ["-e", "process.stdout.write(Buffer.from([0xe2]));setImmediate(()=>{process.stdout.write(Buffer.from([0x82,0xac]));process.stderr.write(Buffer.from([0xc0,0xaf]));});"], { timeoutMs: 5000 });
    expect(result.stdout).toBe("€");
    expect(result.stdoutInvalidUtf8).toBe(false);
    expect(result.stderrInvalidUtf8).toBe(true);
    const empty = await runProcess(process.execPath, ["-e", ""], { timeoutMs: 5000 });
    expect(empty.stdoutInvalidUtf8).toBe(false);
    expect(empty.stderrInvalidUtf8).toBe(false);
  });
});
